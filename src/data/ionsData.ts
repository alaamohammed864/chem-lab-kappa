export function findIonById(id: string): IonData | undefined {
  return COMMON_IONS_DATA.find((i) => i.id === id);
}

export function findIonBySymbolOrFormula(query: string): IonData | undefined {
  const q = query.trim().toLowerCase();
  return COMMON_IONS_DATA.find(
    (i) =>
      i.id.toLowerCase() === q ||
      i.name.toLowerCase() === q ||
      i.formula.toLowerCase() === q ||
      i.symbol.toLowerCase() === q ||
      i.plainFormula.toLowerCase() === q
  );
}

